create sequence if not exists seq_matricula_academica start 1000;

create or replace function gerar_proxima_matricula()
returns text as $$
begin
  return to_char(now(), 'YYYY') || '.' || 
         case when extract(month from now()) <= 6 then '1' else '2' end || '.' || 
         lpad(nextval('seq_matricula_academica')::text, 4, '0');
end;
$$ language plpgsql;

create table if not exists alunos (
  id uuid default gen_random_uuid() primary key,
  nome text not null,
  matricula text not null unique default gerar_proxima_matricula(),
  curso text not null,
  campus text not null,
  email text not null unique,
  senha text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists usuarios (
  id uuid default gen_random_uuid() primary key,
  nome text not null,
  matricula text not null unique default gerar_proxima_matricula(),
  email text not null unique,
  senha text not null,
  cargo text not null default 'aluno',
  status text not null default 'ativo',
  curso text not null default 'Análise e Desenvolvimento de Sistemas',
  campus text not null default 'Campus Grand Shopping',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table if exists usuarios alter column matricula set default gerar_proxima_matricula();
alter table if exists alunos alter column matricula set default gerar_proxima_matricula();

create table if not exists disciplinas (
  id bigint generated by default as identity primary key,
  aluno_matricula text default '2026.2.0491',
  nome text not null,
  professor text not null,
  nota1 numeric(3,1) not null default 0.0,
  nota2 numeric(3,1) not null default 0.0,
  frequencia integer not null default 100,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists avisos (
  id bigint generated by default as identity primary key,
  titulo text not null,
